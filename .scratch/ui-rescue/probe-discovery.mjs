import { existsSync, mkdirSync } from "node:fs";
import { chromium } from "playwright-core";
const executablePath = ["C:/Users/Duy/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe"].find(existsSync);
const ORIGIN = process.env.UI_ORIGIN ?? "http://localhost:5173";
const OUT = ".scratch/ui-rescue/shots"; mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("request", (r) => { if (r.method() === "POST" && r.url().includes("/api/")) console.log("POST", r.url(), (r.postData()??"").slice(0,400)); });
await page.goto(`${ORIGIN}/discovery`, { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
await page.getByLabel("Relative Strength Index").check();
await page.getByLabel("Composite size").fill("2");
await page.getByLabel("Candidate limit").fill("6");
await page.getByLabel("Seed").fill("ui-rescue-pass2");
await page.getByRole("button", { name: "Start Search" }).click();
await page.waitForFunction(() => /Status: (stopped|completed|cancelled)/.test(document.body.innerText), null, { timeout: 120000 }).catch(()=>console.log("TIMEOUT"));
await page.waitForTimeout(2000);
await page.screenshot({ path: `${OUT}/discovery-result.png`, fullPage: true });
console.log((await page.evaluate(() => document.body.innerText)).slice(600, 3200));
await browser.close();
